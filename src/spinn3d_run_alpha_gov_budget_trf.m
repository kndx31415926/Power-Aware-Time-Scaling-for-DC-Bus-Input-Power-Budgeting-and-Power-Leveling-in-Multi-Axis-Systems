    'teacher_policy_command_grid_points',double(getdef(DSi, ...
        'teacher_policy_command_grid_points',NaN)), ...
    'teacher_policy_seed_accept_count',double(getdef(DSi, ...
        'teacher_policy_seed_accept_count',NaN)), ...
    'teacher_policy_fallback_select_count',double(getdef(DSi, ...
        'teacher_policy_fallback_select_count',NaN)), ...
    'teacher_policy_preview_candidate_evaluations',double( ...
        getdef(DSi, ...
            'teacher_policy_preview_candidate_evaluations',NaN)), ...
    'teacher_successor_candidate_evaluations',double(getdef(DSi, ...
        'teacher_successor_candidate_evaluations',NaN)), ...
    'teacher_recursive_viability_check_count',double(getdef(DSi, ...
        'teacher_recursive_viability_check_count',NaN)), ...
    'teacher_recursive_viability_success_count',double(getdef(DSi, ...
        'teacher_recursive_viability_success_count',NaN)), ...
    'teacher_adaptive_expansion_policy_tick_count',double(getdef(DSi, ...
        'teacher_adaptive_expansion_policy_tick_count',NaN)), ...
    'teacher_transition_refinement_evaluations',double(getdef(DSi, ...
        'teacher_transition_refinement_evaluations',NaN)), ...
    'teacher_tau_reserve_met_policy_tick_count',double(getdef(DSi, ...
        'teacher_tau_reserve_met_policy_tick_count',NaN)), ...
    'teacher_qdd_reserve_met_policy_tick_count',double(getdef(DSi, ...
        'teacher_qdd_reserve_met_policy_tick_count',NaN)), ...
    'teacher_feature_materialization_schema',char(getdef(DSi, ...
        'teacher_feature_materialization_schema','')), ...
    'teacher_policy_hard_admission_plant_step_count',double( ...
        getdef(DSi, ...
            'teacher_policy_hard_admission_plant_step_count',NaN)), ...
    'raw_plant_step_count',double(getdef(DSi, ...
        'raw_plant_step_count',NaN)), ...
    'pavg_role',char(getdef(DSi,'pavg_role','')), ...
    'pavg_hard_rejection_enable',logical(getdef(DSi, ...
        'pavg_hard_rejection_enable',true)), ...
    'Pgrid_avg_initial',double(getdef(DSi, ...
        'Pgrid_avg_initial',NaN)), ...
    'Pgrid_avg_final',double(getdef(DSi, ...
        'Pgrid_avg_final',NaN)), ...
    'Pavg_target_W',double(getdef(DSi, ...
        'Pavg_target_W',NaN)), ...
    'Pgrid_avg_peak_W',double(getdef(DSi, ...
        'Pgrid_avg_peak_W',NaN)), ...
    'Pavg_excess_peak_W',double(getdef(DSi, ...
        'Pavg_excess_peak_W',NaN)), ...
    'Pavg_excess_peak_fraction',double(getdef(DSi, ...
        'Pavg_excess_peak_fraction',NaN)), ...
    'Pavg_excess_integral_J',double(getdef(DSi, ...
        'Pavg_excess_integral_J',NaN)), ...
    'Pavg_excess_sq_normalized_integral_s',double(getdef(DSi, ...
        'Pavg_excess_sq_normalized_integral_s',NaN)), ...
    'Pavg_excess_sq_normalized_time_mean',double(getdef(DSi, ...
        'Pavg_excess_sq_normalized_time_mean',NaN)), ...
    'Pavg_exceed_duration_s',double(getdef(DSi, ...
        'Pavg_exceed_duration_s',NaN)), ...
    'Pavg_exceed_plant_step_count',double(getdef(DSi, ...
        'Pavg_exceed_plant_step_count',NaN)), ...
    'teacher_pavg_target_met_policy_tick_count',double( ...
        getdef(DSi, ...
        'teacher_pavg_target_met_policy_tick_count',NaN)), ...
    'teacher_pavg_soft_fallback_policy_tick_count',double( ...
        getdef(DSi, ...
        'teacher_pavg_soft_fallback_policy_tick_count',NaN)), ...
    'teacher_selected_Pavg_next_peak_W',double(getdef(DSi, ...
        'teacher_selected_Pavg_next_peak_W',NaN)));
bus_feature_dim = double(getdef(DSi,'bus_feature_dim',0));
sampling_audit_c.accepted_trajectory_count = ...
    sampling_audit_c.accepted_trajectory_count + 1;
sampling_audit_c.kept_sample_count = ...
    sampling_audit_c.kept_sample_count + numel(DSi.y);
sampling_audit_c.raw_policy_tick_count = ...
    sampling_audit_c.raw_policy_tick_count + ...
    double(getdef(DSi,'raw_policy_tick_count',numel(DSi.y)));
Trajectory = struct('identity',identity,'complete',true, ...
    'Xseq',single(DSi.Xseq),'y',single(DSi.y(:)), ...
    'policy_state',DSi.policy_state,'meta',meta, ...
    'bus_feature_dim',bus_feature_dim,'sampling_audit',sampling_audit_c);
file = fullfile(stage_dir,'trajectory.mat');
save(file,'Trajectory','identity','-v7.3');
[ok,msg]=movefile(stage_dir,final_dir);

end

