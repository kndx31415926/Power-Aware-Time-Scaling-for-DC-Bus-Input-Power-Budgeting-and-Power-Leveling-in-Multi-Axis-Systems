function [q,dq,P]=sample_initial_tracking_state_local(TRAJ,alpha_min,A,traj_id)
[q0,dqg0,~]=TRAJ.eval(0); q0=double(q0(:).'); dq0=alpha_min*double(dqg0(:).');
nJ=numel(q0); eq=zeros(1,nJ); edq=zeros(1,nJ);
if logical(A.enable) && mod(traj_id-1,double(A.nominal_anchor_period))~=0
    qr=expand_state_bound_local(A.q_error_max_rad,nJ);
    dqr=expand_state_bound_local(A.dq_error_max_rad_s,nJ);
    eq=(2*rand(1,nJ)-1).*qr;
    edq=(2*rand(1,nJ)-1).*dqr;
end
% Do not clip into feasibility or change the task distribution.  The complete
% CTC rollout must establish actual physical recovery and endpoint settling.
q=q0+eq; dq=dq0+edq;
P=struct('schema',char(A.schema),'q_error',eq,'dq_error',edq, ...
    'nominal_anchor',~any(eq~=0 | edq~=0));
end

