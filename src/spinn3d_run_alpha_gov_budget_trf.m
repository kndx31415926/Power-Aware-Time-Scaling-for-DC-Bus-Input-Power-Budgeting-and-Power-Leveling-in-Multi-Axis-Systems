function req(S, keys)
if ischar(keys), keys={keys}; end
for i=1:numel(keys)

end
end

function out = ternary_local(condition,when_true,when_false)
if logical(condition)
    out = when_true;
else
    out = when_false;
end
end

function val = getdef(S, f, def)
if isstruct(S) && isfield(S,f) && ~isempty(S.(f))
    val = S.(f);
else
    val = def;
end
end

function q = sample_box(Qdeg)
lo=Qdeg(:,1).'; hi=Qdeg(:,2).'; q=lo+(hi-lo).*rand(size(lo));
end

function ids = parse_ids(names, pat)
ids = [];
for i = 1:numel(names)
    m = regexp(names{i}, pat, 'tokens', 'once');
    if ~isempty(m), ids(end+1) = str2double(m{1}); end %#ok<AGROW>
end
end

function robot = resolve_robot_from_PB(PB)
robot = [];
if isfield(PB,'robot') && isfield(PB.robot,'object') && ~isempty(PB.robot.object), robot = PB.robot.object; return; end
if isfield(PB,'robot') && isfield(PB.robot,'builder') && ~isempty(PB.robot.builder)
    if isfield(PB.robot,'params') && ~isempty(PB.robot.params)
        robot = feval(PB.robot.builder, PB.robot.params);
    else
        robot = feval(PB.robot.builder);
    end
    return;
end
error('PB.robot needs object or builder.');
end

