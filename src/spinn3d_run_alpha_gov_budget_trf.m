function out = spinn3d_run_alpha_gov_budget_trf(opts_override)
%SPINN3D_RUN_ALPHA_GOV_BUDGET_TRF
% Generate geometry-domain alpha/governor look-ahead dataset and train the
% selected Transformer or MLP Alpha model. This implementation samples explicit bus state,
% supports bus-state-aware teacher rollout, and stores bus feature metadata.

stage = 'final';
variant = 'physics';
architecture = 'transformer';
existing_corpus_only=false;
if nargin>=1 && ~isempty(opts_override)
    if isfield(opts_override,'architecture'),architecture=char(opts_override.architecture);end
    if isfield(opts_override,'variant'),variant=char(opts_override.variant);end
    if isfield(opts_override,'existing_corpus_only'),existing_corpus_only=opts_override.existing_corpus_only;end
end
PB=spinn3d_params_block();
req(PB, {'paths','sample','power','alpha','caps','fric','alpha_budget', ...
    'time','payload','train_trf','training','physics','bus', ...
    'execution_audit'});
req(PB.paths, {'root','model_alpha','dataset_alpha_gov_seq_master'});
req(PB.sample, {'dt'});
req(PB.time,   {'Ts'});
req(PB.policy, {'dt','hold','update_every_n'});
req(PB.training, {'schema','initialization_schema','task_sampling_schema', ...
    'payload_bin_edges_kg','split_schema'});

req(PB.physics, {'profile_id'});
req(PB.bus, {'Pavg_init_mode'});
req(PB.alpha,  {'alpha_min','alpha_max','itmax'});
req(PB.power,  {'P_TOTAL_MAX'});
req(PB.fric,   {'B','Fc','vel_eps'});
req(PB.alpha_budget, {'n_traj','chunk_traj','pbud_mode','pbud_range', ...
                      'q0_range_deg','qref_range_deg', ...
                      'dls_lambda','dls_w_ori','bez_lift_z','bez_gamma','ns_min', ...
                      'max_rollout_steps','teacher_use_alpha_dot', ...
                      'teacher_pavg_soft_target_select', ...
                      'teacher_pavg_selection_schema', ...
                      'teacher_policy_rollout_admission_enable', ...
                      'teacher_policy_rollout_schema', ...
                      'alpha_dataset_label_schema', ...
                      'teacher_policy_command_grid_points', ...
                      'teacher_internal_margin_W', ...
                      'teacher_minimum_time_gain_s', ...
                      'teacher_speed_deadline_enable', ...
                      'teacher_local_command_offsets', ...
                      'teacher_refine_command_offsets', ...
                      'teacher_successor_command_offsets', ...
                      'teacher_transition_refine_iterations', ...
                      'teacher_recursive_viability_enable', ...
                      'teacher_recursive_horizon_policy_ticks', ...
                      'teacher_successor_global_grid_points', ...
                      'teacher_tau_reserve_ratio', ...
                      'teacher_qdd_reserve_ratio', ...
                      'max_candidate_attempts', ...

                      'sampling_heartbeat_attempts'});
req(PB.alpha_budget,{'state_teacher','state_augmentation','teacher_heartbeat_walltime_s'});
validate_state_augmentation_local(PB.alpha_budget.state_augmentation);
req(PB.control,{'Kp','Kd'});
req(PB.stop,{'ee_tol','dq_tol_rad','stable_time'});
req(PB.payload, {'range'});
req(PB.train_trf, {'enable','K','H','epochs','batch','lr', ...
    'lambda_over','lambda_under','lambda_pinn','pinn_token_decay', ...
    'lambda_pavg_sq','soft_pavg_loss_schema','lambda_speed', ...
    'lambda_end','end_phase','end_width','d_model', ...
    'n_heads','ffn_dim','n_layers','dropout','head_width','activation', ...
    'pinn_residual_weights','executionEnvironment', ...
    'use_bus_state_features','use_bus_state_rollout', ...
    'validation_fraction','split_seed','initialization_seed','batch_order_seed', ...
    'verbose','bus_state_ranges', ...
    'sequence_cache_budget_gib','close_idle_pool_before_training'});
validate_bus_state_ranges_local(PB.train_trf.bus_state_ranges, ...
    PB.bus,'PB.train_trf.bus_state_ranges');
cache_budget_gib = PB.train_trf.sequence_cache_budget_gib;

close_idle_pool = PB.train_trf.close_idle_pool_before_training;

N_TRAJ_CORPUS = double(PB.alpha_budget.n_traj);
N_TRAJ=N_TRAJ_CORPUS;
CHUNK_TRAJ = double(PB.alpha_budget.chunk_traj);

formal_candidate_attempts = double(PB.alpha_budget.max_candidate_attempts);
heartbeat_attempts=double(PB.alpha_budget.sampling_heartbeat_attempts);
active_candidate_attempts=formal_candidate_attempts;
DT         = double(PB.sample.dt);
TS         = double(PB.time.Ts);
POLICY_DT  = double(PB.policy.dt);
policy_ratio = POLICY_DT/TS;

ALPHA_MIN  = double(PB.alpha.alpha_min);
ALPHA_MAX  = double(PB.alpha.alpha_max);
ITMAX      = double(PB.alpha.itmax);

caps0 = PB.caps;
caps0.P_total_max = double(PB.power.P_TOTAL_MAX);
if isfield(PB,'bus') && isstruct(PB.bus)
    caps0.bus = spinn3d_bus_defaults(PB.bus);
    caps0.bus.P_total_max = caps0.P_total_max;
    if isfield(PB.bus,'eta_share') && ~isempty(PB.bus.eta_share), caps0.eta_share = double(PB.bus.eta_share); end
    if isfield(PB.bus,'P_dump_max') && ~isempty(PB.bus.P_dump_max), caps0.P_dump_max = double(PB.bus.P_dump_max); end
    if isfield(PB.bus,'P_brk_peak') && ~isempty(PB.bus.P_brk_peak), caps0.P_brk_peak = double(PB.bus.P_brk_peak); end
    bus_cap_fields = {'P_grid_peak_max','P_avg_window_s','P_avg_target_frac','P_avg_hard_enable'};
    for ibcf = 1:numel(bus_cap_fields)
        fbc = bus_cap_fields{ibcf};
        if isfield(PB.bus,fbc) && ~isempty(PB.bus.(fbc))
            caps0.(fbc) = PB.bus.(fbc);
        end
    end
end

areg = PB.alpha_reg;
req(areg, {'beta','a_dot_up','a_dot_dn'});

use_bus_state_features = logical(PB.train_trf.use_bus_state_features);
use_bus_state_rollout  = logical(PB.train_trf.use_bus_state_rollout);

robot = resolve_robot_from_PB(PB);
try, robot.DataFormat='row'; end
cfg_trajectory = spinn3d_params_to_cfg(PB,'demo_alpha');
cfg_trajectory.DISABLE_PLOT = true;
% The Alpha label admission reuses the centrally signed deployed hard

% includes the exact q-limit/braking-viability semantics.
caps0.q_min = cfg_trajectory.CAPS.q_min;
caps0.q_max = cfg_trajectory.CAPS.q_max;
caps0.qdd_cmd_max_actual = ...
    cfg_trajectory.CAPS.qdd_cmd_max_actual;
caps0.execution_audit = cfg_trajectory.EXECUTION_AUDIT;

SAVE_DIR = char(PB.paths.root);
if ~exist(SAVE_DIR,'dir'), mkdir(SAVE_DIR); end

% One client owns shared chunks/master/model; workers only own their caches.
chunk_pat = fullfile(SAVE_DIR, 'alpha_gov_seq_v98r5_ds_chunk_*.mat');
req(PB.alpha_budget, {'dataset_seed', ...
    'training_sample_stride_policy_ticks','max_samples_per_traj', ...
    'sample_selection_schema','verbose_sampling'});
dataset_seed = double(PB.alpha_budget.dataset_seed);

sample_stride = double( ...
    PB.alpha_budget.training_sample_stride_policy_ticks);
sample_cap = double(PB.alpha_budget.max_samples_per_traj);
selection_schema = char(PB.alpha_budget.sample_selection_schema);
verbose_sampling = logical(PB.alpha_budget.verbose_sampling);

data_signature = alpha_data_signature_local(PB,caps0,TS,POLICY_DT, ...
    use_bus_state_features,use_bus_state_rollout,dataset_seed, ...
    sample_stride,sample_cap,selection_schema);
if strcmp(architecture,'mlp')
    req(PB,{'train_mlp'}); req(PB.train_mlp,{'hidden_widths','activation'});
    if strcmp(variant,'supervised')
        req(PB.paths,{'model_alpha_mlp_supervised'});
        model_path=char(PB.paths.model_alpha_mlp_supervised);
    else
        req(PB.paths,{'model_alpha_mlp'});
        model_path=char(PB.paths.model_alpha_mlp);
    end
else
    model_path=char(PB.paths.model_alpha);
    if strcmp(variant,'supervised')
        req(PB.paths,{'model_alpha_supervised'});
        model_path=char(PB.paths.model_alpha_supervised);
    end
end
fprintf('[training] %s / %s: %d trajectories.\n',architecture,variant,N_TRAJ);
master_mat = char(PB.paths.dataset_alpha_gov_seq_master);
if existing_corpus_only

    
end
chunk_info = scan_alpha_chunks_local(chunk_pat,data_signature, ...
    double(PB.train_trf.K));
accepted_existing = sum([chunk_info.nAccepted]);
if existing_corpus_only

end
if accepted_existing > N_TRAJ
    error('spinn3d:AlphaChunkCountExceedsTarget', ...
        ['Compatible chunks contain %d accepted trajectories, exceeding the ', ...
         'configured target %d.  Nothing was deleted; reconcile the versioned ', ...
         'directory manually.'],accepted_existing,N_TRAJ);
end
if accepted_existing > 0
    fprintf('[alpha-gov-trf] resume: %d/%d accepted trajectories already present in %d chunk(s).\n', ...
        accepted_existing,N_TRAJ,numel(chunk_info));
end

if exist(master_mat,'file')==2

    fprintf(['[alpha-gov-trf] complete compatible master found; training can ', ...
        'resume without rebuilding it (chunks present: %d/%d trajectories).\n'], ...
        accepted_existing,N_TRAJ);
else

    if isempty(chunk_info)
        next_chunk_id = 1;
    else
        next_chunk_id = max([chunk_info.id]) + 1;
    end

    % Resource controls do not change the signed scientific sampling contract.
    % Each worker owns one trajectory cache; only this client writes chunks.
    generation_context = struct( ...
    'PB',PB, ...
    'caps0',caps0, ...
    'cfg_trajectory',cfg_trajectory, ...
    'dataset_seed',dataset_seed, ...
    'N_TRAJ',N_TRAJ, ...
    'active_candidate_attempts',active_candidate_attempts, ...
    'verbose_sampling',verbose_sampling, ...
    'heartbeat_attempts',heartbeat_attempts, ...
    'DT',DT, ...
    'TS',TS, ...
    'POLICY_DT',POLICY_DT, ...
    'ALPHA_MIN',ALPHA_MIN, ...
    'ALPHA_MAX',ALPHA_MAX, ...
    'ITMAX',ITMAX, ...
    'areg',areg, ...
    'use_bus_state_features',use_bus_state_features, ...
    'use_bus_state_rollout',use_bus_state_rollout, ...
    'sample_stride',sample_stride, ...
    'sample_cap',sample_cap, ...
    'selection_schema',selection_schema);
    generation_context.identity = struct( ...
        'schema','alpha_independent_trajectory_v1', ...
        'data_signature',data_signature, ...
        'task_q0_jitter_deg',double(PB.training.q0_jitter_deg), ...
        'task_qf_jitter_deg',double(PB.training.qf_jitter_deg), ...
        'feature_sample_dt_s',double(DT));
    generation_context.cache_dir=fullfile(SAVE_DIR,'trajectories');
    if ~isfolder(generation_context.cache_dir),mkdir(generation_context.cache_dir);end
    pending_ids = (accepted_existing+1):N_TRAJ;
    for cache_id = pending_ids
        cache_folder = alpha_trajectory_folder_local(generation_context,cache_id);
        if isfolder(cache_folder)
            spinn3d_read_alpha_trajectory(cache_folder,generation_context,cache_id,false);
        end
    end
    if ~isempty(pending_ids)
        is_cached = arrayfun(@(id)isfolder(alpha_trajectory_folder_local( ...
            generation_context,id)),pending_ids);
        pending_ids = pending_ids(~is_cached);
    end
    for trajectory_id=pending_ids
        generate_alpha_trajectory_local(trajectory_id,generation_context);
    end

    accepted_now = accepted_existing;
    while accepted_now < N_TRAJ
        m = min(CHUNK_TRAJ,N_TRAJ-accepted_now);
        meta_c = empty_alpha_meta_local(m);
        bus_feature_dim_c = zeros(m,1);
        sampling_audit_c = empty_sampling_audit_local();

        % chunk.  Only DSi for the current trajectory is resident; neither a
        % CHUNK_TRAJ-sized cell concatenation nor a corpus-sized X tensor is
        % materialised in RAM.
        chunk_signature = data_signature;
        fn_chunk = fullfile(SAVE_DIR,sprintf( ...
            'alpha_gov_seq_v98r5_ds_chunk_%d.mat',next_chunk_id));
        if exist(fn_chunk,'file')==2
            error('spinn3d:AlphaChunkAlreadyExists', ...
                ['Refusing to overwrite chunk %s.  Existing files were left ', ...
                 'untouched; inspect the directory manually.'],fn_chunk);
        end
        tmp_chunk = [tempname(SAVE_DIR),'.partial.mat'];
        save(tmp_chunk,'chunk_signature','-v7.3');
        chunk_store = matfile(tmp_chunk,'Writable',true);
        chunk_sample_count = 0;

        for i = 1:m
            traj_id = accepted_now + i;
            cache_folder = alpha_trajectory_folder_local(generation_context,traj_id);
            Trajectory = spinn3d_read_alpha_trajectory( ...
                cache_folder,generation_context,traj_id,true);
            DSi = Trajectory;
            Xi = single(DSi.Xseq);
            yi = single(DSi.y(:));
            ids_i = repmat(double(traj_id),numel(yi),1);
            ns_i = numel(yi);
            rows_i = chunk_sample_count + (1:ns_i);
            if chunk_sample_count==0
                chunk_store.Xseq_c = Xi;
                chunk_store.y_c = yi;
                chunk_store.traj_id_c = ids_i;
            else
                chunk_store.Xseq_c(rows_i,1:size(Xi,2),1:size(Xi,3)) = Xi;
                chunk_store.y_c(rows_i,1) = yi;
                chunk_store.traj_id_c(rows_i,1) = ids_i;
            end
            chunk_store.policy_q_c(rows_i,1:size(DSi.policy_state.q,2))=DSi.policy_state.q;
            chunk_store.policy_dq_c(rows_i,1:size(DSi.policy_state.dq,2))=DSi.policy_state.dq;
            chunk_store.policy_s_c(rows_i,1)=DSi.policy_state.s;
            chunk_store.policy_a_prev_c(rows_i,1)=DSi.policy_state.a_prev;
            chunk_store.policy_Pavg_c(rows_i,1)=DSi.policy_state.Pavg;
            chunk_sample_count = chunk_sample_count + ns_i;
            meta_c(i,1) = Trajectory.meta;
            bus_feature_dim_c(i,1) = Trajectory.bus_feature_dim;
            sampling_audit_c = add_sampling_audit_local( ...
                sampling_audit_c,Trajectory.sampling_audit);
            clear Xi yi ids_i DSi Trajectory
        end

        clear chunk_store
        save(tmp_chunk,'meta_c', ...
            'bus_feature_dim_c','caps0','PB','use_bus_state_features', ...
            'use_bus_state_rollout','sampling_audit_c','-append');
        if exist(fn_chunk,'file')==2
            error('spinn3d:AlphaChunkAlreadyExists', ...
                ['Chunk %s appeared while its temporary file was being saved. ', ...
                 'Refusing to overwrite it; temporary file %s was retained ', ...
                 'for manual inspection.'],fn_chunk,tmp_chunk);
        end
        [move_ok,move_msg] = movefile(tmp_chunk,fn_chunk);
        if ~move_ok
            error('spinn3d:AlphaChunkCommitFailed', ...
                ['Could not commit temporary chunk %s to %s (%s).  The ', ...
                 'temporary file was not deleted.'],tmp_chunk,fn_chunk,move_msg);
        end
        fprintf(['[alpha-gov-trf] wrote new chunk #%d: %s | accepted=%d, ', ...
            'samples=%d, draws=%d, branch-reject=%d, generator-reject=%d\n'], ...
            next_chunk_id,fn_chunk,m,chunk_sample_count, ...
            sampling_audit_c.candidate_draw_count, ...
            sampling_audit_c.branch_prefilter_reject_count, ...
            sampling_audit_c.generator_reject_count);
        accepted_now = accepted_now + m;
        next_chunk_id = next_chunk_id + 1;
    end

    chunk_info = scan_alpha_chunks_local(chunk_pat,data_signature, ...
        double(PB.train_trf.K));
    accepted_final = sum([chunk_info.nAccepted]);
    if accepted_final ~= N_TRAJ
        error('spinn3d:AlphaResumeCountMismatch', ...
            ['Expected exactly %d accepted trajectories after resume, found %d. ', ...
             'No files were deleted or overwritten.'],N_TRAJ,accepted_final);
    end
    % The master contains compact metadata plus a manifest of immutable

    % the central client-process cache ceiling, then forms shuffled
    % mini-batches by ordinary in-memory indexing.
    DS = build_master_from_chunks_local(chunk_info,PB,caps0, ...
        data_signature,ALPHA_MIN,ALPHA_MAX,POLICY_DT,use_bus_state_features, ...
        use_bus_state_rollout,sample_stride,sample_cap,selection_schema);
    master_signature = data_signature;
    master_summary = struct('schema','alpha_master_summary_v5_chunked', ...
        'accepted_trajectory_count',double(N_TRAJ), ...
        'sample_count',double(numel(DS.y)), ...
        'K',double(DS.K), ...
        'feature_dim',double(DS.expected_feature_dim), ...
        'storage_precision',char(DS.storage_precision));
    if exist(master_mat,'file')==2
        error('spinn3d:AlphaMasterAlreadyExists', ...
            ['Refusing to overwrite master %s.  Existing files were left ', ...
             'untouched.'],master_mat);
    end
    tmp_master = [tempname(SAVE_DIR),'.partial.mat'];
    save(tmp_master,'DS','master_signature','master_summary','-v7.3');
    if exist(master_mat,'file')==2
        error('spinn3d:AlphaMasterAlreadyExists', ...
            ['Master %s appeared while its temporary file was being saved. ', ...
             'Refusing to overwrite it; temporary file %s was retained ', ...
             'for manual inspection.'],master_mat,tmp_master);
    end
    [move_ok,move_msg] = movefile(tmp_master,master_mat);
    if ~move_ok
        error('spinn3d:AlphaMasterCommitFailed', ...
            ['Could not commit temporary master %s to %s (%s).  The ', ...
             'temporary file was not deleted.'], ...
            tmp_master,master_mat,move_msg);
    end
    fprintf('[alpha-gov-trf] samples=%d | master=%s\n', ...
        numel(DS.y),master_mat);
end

if PB.train_trf.enable
    if ~exist('DS','var') || isempty(DS)
        M = load(master_mat,'DS');
        DS = M.DS;

    end

    % still names the old absolute root.  Bind only to the complete chunk set
    % scanned and validated in the current SAVE_DIR.  This changes DS in
    % memory only; the master and all immutable chunks remain untouched.
    DS = bind_alpha_manifest_to_current_chunks_local( ...
        DS,chunk_info,data_signature,master_mat);

    topts = struct();
    topts.MaxEpochs        = PB.train_trf.epochs;
    topts.MiniBatchSize    = PB.train_trf.batch;
    topts.InitialLearnRate = PB.train_trf.lr;

    topts.LambdaOver = PB.train_trf.lambda_over;
    topts.LambdaUnder = PB.train_trf.lambda_under;
    topts.LambdaPINN = PB.train_trf.lambda_pinn;
    topts.LambdaPavgSq = PB.train_trf.lambda_pavg_sq;
    topts.SoftPavgLossSchema = char(PB.train_trf.soft_pavg_loss_schema);
    topts.LambdaSpeed = PB.train_trf.lambda_speed;
    topts.LambdaEnd = PB.train_trf.lambda_end;
    topts.EndPhase = PB.train_trf.end_phase;
    topts.EndWidth = PB.train_trf.end_width;
    topts.PinnTokenDecay = PB.train_trf.pinn_token_decay;

    topts.DModel = PB.train_trf.d_model;
    topts.NumHeads = PB.train_trf.n_heads;
    topts.FFNDim = PB.train_trf.ffn_dim;
    topts.NumLayers = PB.train_trf.n_layers;
    topts.Dropout = PB.train_trf.dropout;
    topts.HeadWidth = PB.train_trf.head_width;
    topts.Activation = lower(char(PB.train_trf.activation));
    topts.PINNWeights = PB.train_trf.pinn_residual_weights;
    topts.ExecutionEnvironment = PB.train_trf.executionEnvironment;
    topts.ValidationFraction = PB.train_trf.validation_fraction;
    topts.SplitSeed = PB.train_trf.split_seed;
    topts.InitializationSeed=PB.train_trf.initialization_seed;
    topts.BatchOrderSeed=PB.train_trf.batch_order_seed;
    topts.Architecture=architecture;
    topts.MLPHiddenWidths=[];
    topts.MLPActivation='';
    if strcmp(architecture,'mlp')
        topts.MLPHiddenWidths=double(PB.train_mlp.hidden_widths(:).');
        topts.MLPActivation=lower(char(PB.train_mlp.activation));
    end
    topts.Verbose = PB.train_trf.verbose;
    topts.SequenceCacheBudgetGiB = ...
        double(PB.train_trf.sequence_cache_budget_gib);
    topts.ModelRole = 'alpha_only_final_for_paper';
    if strcmp(variant,'supervised')
        topts.ModelRole='alpha_only_supervised_for_ablation';
        topts.LambdaPINN=0;
        topts.LambdaPavgSq=0;
        % Terminal velocity is predicted by the mechanical model, so it
        % belongs to the removed physics group, not teacher supervision.
        topts.LambdaEnd=0;
    end

    topts.CAPS = caps0;
    topts.FRIC = PB.fric;
    fprintf('[alpha-train] %s / %s: epochs=%d, batch=%d, lr=%.3g | exec=%s | model=%s\n', ...
        architecture,variant,topts.MaxEpochs, topts.MiniBatchSize, topts.InitialLearnRate, char(topts.ExecutionEnvironment), model_path);

    trained = spinn3d_train_alpha_gov_trf(DS, model_path, topts);
end

out = struct('dataset_master',master_mat,'model',model_path, ...
    'architecture',architecture,'variant',variant);
end

