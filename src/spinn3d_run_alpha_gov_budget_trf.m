use_bus_state_features = C.use_bus_state_features;
use_bus_state_rollout = C.use_bus_state_rollout;
sample_stride = C.sample_stride;
sample_cap = C.sample_cap;
selection_schema = C.selection_schema;
robot = resolve_robot_from_PB(PB);
try, robot.DataFormat='row'; end
stage_token=strrep(char(java.util.UUID.randomUUID()),'-','');
stage_dir = fullfile(C.cache_dir,sprintf('.t%06d_%s',traj_id,stage_token(1:12)));

mkdir(stage_dir);

% sealed completed directory is ever admitted on resume.
identity = C.identity;
identity.traj_id = double(traj_id);
identity.trajectory_seed = double(dataset_seed+traj_id-1);

sampling_audit_c = empty_sampling_audit_local();
rng(dataset_seed + traj_id - 1,'twister');
trajectory_clock = tic;
stratum=spinn3d_training_stratum(PB,traj_id);
fprintf('[alpha-gov-trf] trajectory %d/%d start | load band %d [%.3f, %.3f] kg | template %d\n', ...
    traj_id,N_TRAJ,stratum.payload_group,stratum.mass_bounds_kg(1), ...
    stratum.mass_bounds_kg(2),stratum.template_index);
candidate_attempt = 0;
while true
    if candidate_attempt >= active_candidate_attempts
        error('spinn3d:AlphaDatasetSamplingExhausted', ...
            ['Could not obtain one physically feasible alpha trajectory ', ...
             'after %d deterministic candidate draws for accepted ', ...
             'trajectory %d, load band %d [%.3f, %.3f] kg, template %d ', ...
             '(elapsed %.1f s). Last rejection: %s: %s. ', ...
             'The layer was not changed; existing chunks were left untouched.'], ...
            active_candidate_attempts,traj_id,stratum.payload_group, ...
            stratum.mass_bounds_kg(1),stratum.mass_bounds_kg(2), ...
            stratum.template_index,toc(trajectory_clock), ...
            char(sampling_audit_c.last_rejection_id), ...
            char(sampling_audit_c.last_rejection_message));
    end
    candidate_attempt = candidate_attempt + 1;
    candidate_clock=tic; initial_perturbation=struct();
    sampling_audit_c.candidate_draw_count = ...
        sampling_audit_c.candidate_draw_count + 1;
    if verbose_sampling && ...
            (candidate_attempt==1 || mod(candidate_attempt,heartbeat_attempts)==0)
        fprintf(['[alpha-gov-trf] trajectory %d/%d | candidate ', ...
            '%d/%d | elapsed %.1f s\n'],traj_id,N_TRAJ, ...
            candidate_attempt,active_candidate_attempts, ...
            toc(trajectory_clock));
    end

    task_seed=mod(dataset_seed+traj_id-1+1000003*(candidate_attempt-1),2^32-1);
    [task_cfg,task_meta]=spinn3d_r6_sample_task(PB,task_seed,traj_id,'training');
    q0d=double(task_cfg.Q0_DEG(:));
    qrefd=double(task_cfg.QF_DEG(:));
    q0 = deg2rad_local(q0d);
    qf = deg2rad_local(qrefd);

    branch = spinn3d_endpoint_yaw_branch_check(robot,q0,qf,[]);
    if branch.available && ~branch.compatible
        sampling_audit_c.branch_prefilter_reject_count = ...
            sampling_audit_c.branch_prefilter_reject_count + 1;
        sampling_audit_c.last_rejection_id = ...
            'make_traj_cart_bezier_dls:BranchTopology';
        sampling_audit_c.last_rejection_message = sprintf( ...
            'rho0=%.6g m, rhof=%.6g m', ...
            branch.rho0_m,branch.rhof_m);
        if verbose_sampling && ...
                (candidate_attempt<=3 || mod(candidate_attempt,heartbeat_attempts)==0)
            fprintf(['[alpha-gov-trf] branch prefilter reject ', ...
                'trajectory %d draw %d: rho0=%.6g m, rhof=%.6g m\n'], ...
                traj_id,candidate_attempt,branch.rho0_m,branch.rhof_m);
        end
        sampling_audit_c=append_attempt_local(sampling_audit_c, ...
            traj_id,candidate_attempt,dataset_seed+traj_id-1,'branch_rejected', ...
            toc(candidate_clock),sampling_audit_c.last_rejection_id, ...
            sampling_audit_c.last_rejection_message,initial_perturbation);

        continue;
    end

    try
        if strcmpi(PB.alpha_budget.pbud_mode,'fixed')
            pbud = PB.power.P_TOTAL_MAX;
        elseif mod(traj_id-1, ...
                PB.alpha_budget.pbud_nominal_anchor_period) == 0
            pbud = PB.power.P_TOTAL_MAX;
        elseif mod(traj_id-1, ...
                PB.alpha_budget.pbud_upper_anchor_period) == ...
                PB.alpha_budget.pbud_upper_anchor_phase
            pbud = max(PB.alpha_budget.pbud_range);
        else
            pbud = PB.alpha_budget.pbud_range(1) + rand() * ...
                (PB.alpha_budget.pbud_range(2)-PB.alpha_budget.pbud_range(1));
        end
        caps_use = caps0;
        caps_use.P_total_max = pbud;
        caps_use.bus.P_total_max = pbud;
        cfg_geom = cfg_trajectory;
        cfg_geom.Q0_DEG = rad2deg(q0(:));
        cfg_geom.QF_DEG = rad2deg(qf(:));
        cfg_geom.P_TOTAL_MAX = pbud;
        cfg_geom.CAPS = caps_use;
        if isfield(cfg_geom,'BUS') && isstruct(cfg_geom.BUS)
            cfg_geom.BUS.P_total_max = pbud;
        end
        payload_struct = task_cfg.PAYLOAD.DEMO;
        % Geometry, work-plane clearance, payload OBB and the
        % dynamically timed reference must all see the same
        % sampled payload later used by label rollout.  Building
        % with the zero-mass base tool would silently skip the
        % centrally required positive-mass payload check.
        [robot_geom,~] = spinn3d_inject_payload_last_body( ...
            robot,payload_struct);
        TRAJ = make_traj_cart_bezier_dls( ...
            robot_geom,q0,qf,caps_use,cfg_geom);

        cfgBus = struct();
        if isfield(PB,'bus') && isstruct(PB.bus)
            cfgBus.BUS = PB.bus;
        else
            cfgBus.BUS = struct();
        end
        cfgBus.P_TOTAL_MAX = pbud;
        bus = get_bus_from_cfg(cfgBus,pbud);

        % A new stationary task has a known physical prehistory: constant
        % payload hold. Let the shared dataset initializer compute its source/
        % load voltage equilibrium and the corresponding nonzero power EMA.
        % Never invent an EMA from the first millisecond of a random Vdc draw.
        st_bus0 = [];

        opts = struct('dt',DT,'Ts',TS,'alpha_min',ALPHA_MIN, ...
            'alpha_max',ALPHA_MAX, ...
            'itmax',ITMAX, ...
            'fric',struct('B',double((PB.fric.B(:)).'), ...
                         'Fc',double((PB.fric.Fc(:)).'), ...
                         'vel_eps',double(PB.fric.vel_eps)), ...
            'payload',payload_struct, ...
            'BETA',double(areg.beta), ...
            'A_DOT_UP',double(areg.a_dot_up), ...
            'A_DOT_DN',double(areg.a_dot_dn), ...
            'K',double(PB.train_trf.K), ...
            'H',double(PB.train_trf.H), ...
            'policy_dt',POLICY_DT, ...
            'bus',bus,'bus_state',st_bus0, ...
            'use_bus_state_features',use_bus_state_features, ...
            'use_bus_state_rollout',use_bus_state_rollout, ...
            'training_sample_stride_policy_ticks',sample_stride, ...
            'max_samples_per_traj',sample_cap, ...
            'sample_selection_schema',selection_schema, ...
            'max_rollout_steps',double(PB.alpha_budget.max_rollout_steps), ...
            'teacher_use_alpha_dot', ...
                logical(PB.alpha_budget.teacher_use_alpha_dot), ...
            'teacher_pavg_soft_target_select', ...
                logical(PB.alpha_budget.teacher_pavg_soft_target_select), ...
            'teacher_pavg_selection_schema', ...
                char(PB.alpha_budget.teacher_pavg_selection_schema), ...
            'teacher_policy_rollout_admission_enable', ...
                logical(PB.alpha_budget. ...
                    teacher_policy_rollout_admission_enable), ...
            'teacher_policy_rollout_schema', ...
                char(PB.alpha_budget. ...
                    teacher_policy_rollout_schema), ...
            'alpha_dataset_label_schema', ...
                char(PB.alpha_budget.alpha_dataset_label_schema), ...
            'teacher_policy_command_grid_points', ...
                double(PB.alpha_budget. ...
                    teacher_policy_command_grid_points), ...
            'teacher_local_command_offsets',double( ...
                PB.alpha_budget.teacher_local_command_offsets), ...
            'teacher_refine_command_offsets',double( ...
                PB.alpha_budget.teacher_refine_command_offsets), ...
            'teacher_successor_command_offsets',double( ...
                PB.alpha_budget.teacher_successor_command_offsets), ...
            'teacher_transition_refine_iterations',double( ...
                PB.alpha_budget.teacher_transition_refine_iterations), ...
            'teacher_recursive_viability_enable',logical( ...
                PB.alpha_budget.teacher_recursive_viability_enable), ...
            'teacher_recursive_horizon_policy_ticks',double( ...
                PB.alpha_budget.teacher_recursive_horizon_policy_ticks), ...
            'teacher_successor_global_grid_points',double( ...
                PB.alpha_budget.teacher_successor_global_grid_points), ...
            'teacher_tau_reserve_ratio',double( ...
                PB.alpha_budget.teacher_tau_reserve_ratio), ...
            'teacher_qdd_reserve_ratio',double( ...
                PB.alpha_budget.teacher_qdd_reserve_ratio), ...
            'teacher_internal_margin_W',double( ...
                PB.alpha_budget.teacher_internal_margin_W), ...
            'teacher_minimum_time_gain_s',double( ...
                PB.alpha_budget.teacher_minimum_time_gain_s), ...
            'teacher_speed_deadline_enable',logical( ...
                PB.alpha_budget.teacher_speed_deadline_enable));
        opts.teacher_config=spinn3d_alpha_state_teacher_config( ...
            PB,caps_use,opts.fric,bus,cfg_trajectory.CTRL.Kp, ...
            cfg_trajectory.CTRL.Kd,pbud);
        opts.stop=PB.stop;
        opts.teacher_heartbeat_walltime_s=PB.alpha_budget.teacher_heartbeat_walltime_s;
        opts.ee_name=char(PB.robot.ee_name);
        opts.teacher_max_rollout_duration_s= ...
            double(PB.alpha_budget.state_teacher.max_rollout_duration_factor)* ...
            double(TRAJ.Tf)+double(PB.alpha_budget.state_teacher.max_rollout_extra_s);
        [opts.initial_q,opts.initial_dq,initial_perturbation]= ...
            sample_initial_tracking_state_local(TRAJ,ALPHA_MIN, ...
            PB.alpha_budget.state_augmentation,traj_id);
        opts.state_augmentation_schema=char(PB.alpha_budget.state_augmentation.schema);
        opts.training_initialization_schema=char(PB.training.initialization_schema);
        DSi = spinn3d_make_dataset_alpha_gov_geom_seq( ...
            robot,TRAJ,caps_use,opts);
        % Training labels are retained only after the teacher reaches and
        % holds the prescribed terminal state for the required duration.
        if ~logical(DSi.terminal_reached) || ...
                double(DSi.terminal_stable_duration_s)+1e-12<PB.stop.stable_time
            error('spinn3d:AlphaDatasetPolicyAuditInvalid', ...
                'The teacher trajectory did not complete the terminal hold.');
        end
        fprintf(['[alpha-gov-trf] trajectory %d/%d accepted | ', ...
            'rows=%d | draw=%d | elapsed %.1f s\n'], ...
            traj_id,N_TRAJ,numel(DSi.y),candidate_attempt, ...
            toc(trajectory_clock));
        sampling_audit_c=append_attempt_local(sampling_audit_c, ...
            traj_id,candidate_attempt,dataset_seed+traj_id-1,'accepted', ...
            toc(candidate_clock),'','',initial_perturbation);

        break;
    catch ME_candidate
        if is_expected_alpha_rejection_local(ME_candidate.identifier)
            attempt_status='physical_rejected';
        else
            attempt_status='error';
        end
        sampling_audit_c=append_attempt_local(sampling_audit_c, ...
            traj_id,candidate_attempt,dataset_seed+traj_id-1,attempt_status, ...
            toc(candidate_clock),ME_candidate.identifier,ME_candidate.message, ...
            initial_perturbation);
        if strcmp(attempt_status,'error')

            rethrow(ME_candidate);
        end
        sampling_audit_c.generator_reject_count = ...
            sampling_audit_c.generator_reject_count + 1;
        sampling_audit_c.last_rejection_id = ME_candidate.identifier;
        sampling_audit_c.last_rejection_message = ...
            ME_candidate.message;

        if verbose_sampling && ...
                (candidate_attempt<=3 || mod(candidate_attempt,heartbeat_attempts)==0)
            fprintf(['[alpha-gov-trf] sample reject for ', ...
                'trajectory %d draw %d: %s: %s\n'], ...
                traj_id,candidate_attempt, ...
                ME_candidate.identifier,ME_candidate.message);
        end
    end
end
meta = struct('pbud',pbud,'payload',payload_struct, ...
    'bus',bus,'bus_state0',DSi.bus_state0,'power_init',DSi.power_init,'traj_id',traj_id, ...
    'task_meta',task_meta,'q0_deg',q0d,'qf_deg',qrefd, ...
    'teacher_state_schema',char(DSi.teacher_state_schema), ...
    'state_augmentation_schema',char(DSi.state_augmentation_schema), ...
    'initial_q',DSi.initial_q,'initial_dq',DSi.initial_dq, ...
    'initial_q_error',DSi.initial_q_error,'initial_dq_error',DSi.initial_dq_error, ...
    'terminal_reached',logical(DSi.terminal_reached), ...
    'terminal_ee_error_m',double(DSi.terminal_ee_error_m), ...
    'terminal_dq_max_rad_s',double(DSi.terminal_dq_max_rad_s), ...
    'terminal_dq_norm_rad_s',double(DSi.terminal_dq_norm_rad_s), ...
    'terminal_stable_duration_s',double(DSi.terminal_stable_duration_s), ...
    'rollout_elapsed_s',double(DSi.rollout_elapsed_s), ...
    'teacher_pavg_soft_target_select',logical( ...
        PB.alpha_budget.teacher_pavg_soft_target_select), ...
    'teacher_pavg_selection_schema',char( ...
        PB.alpha_budget.teacher_pavg_selection_schema), ...
    'teacher_policy_rollout_admission_enable',logical( ...
        getdef(DSi, ...
            'teacher_policy_rollout_admission_enable',false)), ...
    'teacher_policy_rollout_schema',char(getdef(DSi, ...
        'teacher_policy_rollout_schema','')), ...
    'alpha_dataset_label_schema',char(getdef(DSi, ...
        'alpha_dataset_label_schema','')), ...
    'teacher_desired_command_dt_s',double(getdef(DSi, ...
        'teacher_desired_command_dt_s',NaN)), ...
    'teacher_applied_governor_dt_s',double(getdef(DSi, ...
