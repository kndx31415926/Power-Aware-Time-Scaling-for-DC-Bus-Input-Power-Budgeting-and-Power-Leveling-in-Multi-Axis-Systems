function tag = spinn3d_bus_contract_fingerprint(bus)
% Text representation of the electrical parameters stored with the data.
bus = spinn3d_bus_defaults(bus);

fields = { ...
    'model','model_scope','auxiliary_topology','motor_power_schema', ...
    'quadrant_power_model','actuator_envelope_model', ...
    'architecture_id','profile_id','routing_mode', ...
    'regen_enable','direct_share_enable', ...
    'V_bus_V','V_nominal_V','motor_friction_smoothing_rad_s', ...
    'I_supply_max_A','servo_parallel', ...
    'I_noload_A','I_stall_A','tau_stall_single_Nm', ...
    'omega_noload_rad_s','omega_operating_max_rad_s','motor_speed_contract','tau_dead_Nm', ...
    'eta_motoring','eta_regen','eta_share','P_idle_W', ...
    'P_total_max','P_grid_peak_max','P_avg_window_s', ...
    'Pavg_init_mode','P_avg_target_frac','P_avg_hard_enable', ...
    'Pregen_peak_max_W','Pshare_peak_max_W', ...
    'enable_state','Ebuf_max_J','Ebuf_min_J','Ebuf_init_J', ...
    'Ereuse_init_J','Pbuf_chg_max_W','Pbuf_dis_max_W', ...
    'eta_buf_chg','eta_buf_dis','P_brk_peak', ...
    'Tamb_C','Tbrk_init_C','Tbrk_max_C', ...
    'Cth_brk_J_per_C','Rth_brk_C_per_W'};

prefix='bus_contract_v97;';
if strcmp(char(bus.model_scope),'dynamic_capacitor_common_dc_v1')
    fields=setdiff(fields,{'P_brk_peak','Tamb_C','Tbrk_init_C','Tbrk_max_C', ...
        'Cth_brk_J_per_C','Rth_brk_C_per_W'},'stable');
    fields=[fields {'brake_model','C_dc_F','R_source_ohm','V_source_V', ...
        'V_min_V','V_max_V','dc_substeps','dc_newton_iterations', ...
        'dc_solver_tolerance_W','V_init_V', ...
        'regen_injection_capacity_semantics'}];
    prefix='bus_contract_v99r7_nobrake;';
end
parts = cell(1,numel(fields));
for i = 1:numel(fields)
    fn = fields{i};
    value = bus.(fn);
    if isnumeric(value) || islogical(value)
        encoded = mat2str(double(value),17);
    elseif ischar(value) || (isstring(value) && isscalar(value))
        encoded = char(value);
    end
    parts{i} = sprintf('%s=%s',fn,encoded);
end
tag = [prefix strjoin(parts,';')];
end
