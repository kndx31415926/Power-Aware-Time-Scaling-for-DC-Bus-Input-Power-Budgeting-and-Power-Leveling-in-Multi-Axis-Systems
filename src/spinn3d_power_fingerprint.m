function fp = spinn3d_power_fingerprint(PB)
% Store the motor and DC-bus parameters with the training data.
B=spinn3d_bus_defaults(PB.bus);
fp=struct();
fp.schema='mathsource99r7_no_brake_motor_bus_physics_v3';
fp.brake_model='none';
fp.bus_contract=spinn3d_bus_contract_fingerprint(B);
fp.V_nominal_V=double(B.V_nominal_V);
fp.motor_friction_smoothing_rad_s=double(B.motor_friction_smoothing_rad_s);
fp.model_scope=char(B.model_scope);
fp.auxiliary_topology=char(B.auxiliary_topology);
fp.motor_power_schema=char(B.motor_power_schema);
fp.P_TOTAL_MAX_W=double(PB.power.P_TOTAL_MAX);
fp.bus_model=char(B.model);
fp.quadrant_power_model=char(B.quadrant_power_model);
fp.actuator_envelope_model=char(B.actuator_envelope_model);
fp.architecture_id=char(B.architecture_id);
fp.profile_id=char(B.profile_id);
fp.routing_mode=char(B.routing_mode);
fp.V_bus_V=double(B.V_bus_V);
fp.I_supply_max_A=double(B.I_supply_max_A);
fp.I_noload_A=double(B.I_noload_A);
fp.I_stall_A=double(B.I_stall_A);
fp.tau_stall_single_Nm=double(B.tau_stall_single_Nm);
fp.omega_noload_rad_s=double(B.omega_noload_rad_s);
fp.omega_operating_max_rad_s=double(B.omega_operating_max_rad_s);
fp.motor_speed_contract=char(B.motor_speed_contract);
fp.tau_dead_Nm=double(B.tau_dead_Nm);
fp.servo_parallel=double(B.servo_parallel);
fp.P_idle_W=double(B.P_idle_W);
fp.P_grid_peak_max_W=double(B.P_grid_peak_max);
fp.P_avg_window_s=double(B.P_avg_window_s);
fp.P_avg_target_frac=double(B.P_avg_target_frac);
fp.P_avg_hard_enable=double(logical(B.P_avg_hard_enable));
fp.regen_enable=double(logical(B.regen_enable));
fp.direct_share_enable=double(logical(B.direct_share_enable));
fp.eta_motoring=double(B.eta_motoring);
fp.eta_regen=double(B.eta_regen);
fp.eta_share=double(B.eta_share);
fp.Pregen_peak_max_W=double(B.Pregen_peak_max_W);
fp.Pshare_peak_max_W=double(B.Pshare_peak_max_W);
fp.enable_state=double(logical(B.enable_state));
fp.Ebuf_max_J=double(B.Ebuf_max_J);
fp.Ebuf_min_J=double(B.Ebuf_min_J);
fp.Ebuf_init_J=double(B.Ebuf_init_J);
fp.Ereuse_init_J=double(B.Ereuse_init_J);
fp.Pbuf_chg_max_W=double(B.Pbuf_chg_max_W);
fp.Pbuf_dis_max_W=double(B.Pbuf_dis_max_W);
fp.eta_buf_chg=double(B.eta_buf_chg);
fp.eta_buf_dis=double(B.eta_buf_dis);
fp.Pavg_init_mode=char(B.Pavg_init_mode);
fp.motor=PB.motor;
end
