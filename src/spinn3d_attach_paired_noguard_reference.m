function [cfg, anchor] = spinn3d_attach_paired_noguard_reference(cfg)
%SPINN3D_ATTACH_PAIRED_NOGUARD_REFERENCE Resolve the exact task time anchor.
% Public optimized/guarded demos call this before planning.  Formal paired
% evaluation already supplies cfg.FAIRNESS.t_reach_noguard_s; a stand-alone
% demo otherwise runs the same full-plant NoGuard case headlessly once.

if nargin < 1 || ~isstruct(cfg)
    error('spinn3d:BadFairnessCfg','A valid cfg struct is required.');
end
if ~isfield(cfg,'FAIRNESS') || ~isstruct(cfg.FAIRNESS)
    cfg.FAIRNESS = struct();
end

% NoGuard anchor is unavailable. This does not grant relative-time success.
if logical(getdef_local(cfg.FAIRNESS,'revision_independent_failure_eval',false)) && ...
        ~logical(getdef_local(cfg.FAIRNESS,'noguard_reference_available',false))
    cfg.FAIRNESS.t_reach_noguard_s=NaN;
    cfg.FAIRNESS.reference_source='paired-noguard-unavailable';
    anchor=make_anchor_local(NaN,NaN,cfg.FAIRNESS.reference_source,empty_soft_reference_local());
    anchor.reference_available=false;
    return;
end

t_ng = getdef_local(cfg.FAIRNESS,'t_reach_noguard_s',NaN);
Tf_ng = getdef_local(cfg.FAIRNESS,'noguard_reference_Tf_s',NaN);
[soft_ref,soft_ref_valid] = ...
    soft_reference_from_fairness_local(cfg.FAIRNESS);
if soft_ref_valid && isnumeric(t_ng) && isreal(t_ng) && ...
        isscalar(t_ng) && isfinite(double(t_ng)) && double(t_ng)>0
    relation_tol=1e-12+1e-10*max([1,soft_ref.integral_s, ...
        soft_ref.mean*double(t_ng)]);
    soft_ref_valid=abs(soft_ref.integral_s- ...
        soft_ref.mean*double(t_ng))<=relation_tol;
end
if isnumeric(t_ng) && isscalar(t_ng) && isfinite(t_ng) && t_ng > 0 && ...
        soft_ref_valid
    cfg.FAIRNESS.reference_source = ...
        'caller-paired-full-plant-with-authoritative-soft-power';
    anchor = make_anchor_local(double(t_ng),double_or_nan_local(Tf_ng), ...
        cfg.FAIRNESS.reference_source,soft_ref);
    return;
end

if logical(getdef_local(cfg.FAIRNESS,'revision_independent_failure_eval',false)) && ...
        logical(getdef_local(cfg.FAIRNESS,'noguard_reference_available',false)) && ...
        isnumeric(t_ng) && isscalar(t_ng) && isfinite(t_ng) && t_ng>0
    cfg.FAIRNESS.reference_source='caller-paired-full-plant';
    anchor=make_anchor_local(double(t_ng),double_or_nan_local(Tf_ng), ...
        cfg.FAIRNESS.reference_source,soft_ref);
    anchor.reference_available=true;
    return;
end

if exist('spinn3d_demo_ctcgov_online_nonn_nolimit','file') ~= 2
    error('spinn3d:MissingNoGuardDemo', ...
        'spinn3d_demo_ctcgov_online_nonn_nolimit.m is required for the paired timing contract.');
end

cfg_ng = cfg;
cfg_ng.DISABLE_PLOT = true;
if ~isfield(cfg_ng,'PLOT') || ~isstruct(cfg_ng.PLOT), cfg_ng.PLOT = struct(); end
cfg_ng.PLOT.enable = false;

% Restore the caller RNG state so NoGuard and the compared method begin
% from the same stochastic state when noise is intentionally enabled.
rng_state = rng;
rng_cleanup = onCleanup(@()rng(rng_state)); %#ok<NASGU>
[out_ng,~] = spinn3d_demo_ctcgov_online_nonn_nolimit(cfg_ng);
if ~isstruct(out_ng) || ~isfield(out_ng,'reached') || ...
        ~is_binary_true_local(out_ng.reached) || ...
        ~isfield(out_ng,'accepted') || ...
        ~is_binary_true_local(out_ng.accepted) || ...
        ~isfield(out_ng,'execution_audit') || ...
        ~isstruct(out_ng.execution_audit) || ...
        ~isfield(out_ng.execution_audit,'pass') || ...
        ~is_binary_true_local(out_ng.execution_audit.pass) || ...
        ~isfield(out_ng,'t_reach') || ...
        ~isnumeric(out_ng.t_reach) || ~isscalar(out_ng.t_reach) || ...
        ~isfinite(out_ng.t_reach) || out_ng.t_reach <= 0
    error('spinn3d:NoGuardReferenceFailed', ...
        ['The paired full-plant NoGuard run must reach and pass its hard ', ...
         'execution audit before it can define a performance reference.']);
end

t_ng = double(out_ng.t_reach);
Tf_ng = NaN;
if isfield(out_ng,'reference') && isstruct(out_ng.reference) && ...
        isfield(out_ng.reference,'Tf') && isnumeric(out_ng.reference.Tf) && ...
        isscalar(out_ng.reference.Tf) && isfinite(out_ng.reference.Tf)
    Tf_ng = double(out_ng.reference.Tf);
elseif isfield(out_ng,'traj_Tf') && isnumeric(out_ng.traj_Tf) && ...
        isscalar(out_ng.traj_Tf) && isfinite(out_ng.traj_Tf)
    Tf_ng = double(out_ng.traj_Tf);
end

cfg.FAIRNESS.t_reach_noguard_s = t_ng;
cfg.FAIRNESS.noguard_reference_Tf_s = Tf_ng;
soft_ref = soft_reference_from_output_local(out_ng);
cfg.FAIRNESS.noguard_soft_reference_available = ...
    logical(soft_ref.available);
cfg.FAIRNESS.noguard_soft_excess_sq_mean = soft_ref.mean;
cfg.FAIRNESS.noguard_soft_excess_sq_integral_s = soft_ref.integral_s;
cfg.FAIRNESS.noguard_soft_budget_W = soft_ref.budget_W;
cfg.FAIRNESS.noguard_soft_reference_source = soft_ref.source;
if soft_ref.available
    cfg.FAIRNESS.reference_source = ...
        'standalone-paired-full-plant-with-authoritative-soft-power';
else
    cfg.FAIRNESS.reference_source = ...
        'standalone-paired-full-plant-soft-power-unavailable';
end
anchor = make_anchor_local(t_ng,Tf_ng, ...
    cfg.FAIRNESS.reference_source,soft_ref);
end

function anchor=make_anchor_local(t_ng,Tf_ng,source,soft_ref)
anchor = struct('t_reach_s',double(t_ng), ...
    'reference_Tf_s',double_or_nan_local(Tf_ng), ...
    'source',char(source), ...
    'soft_reference_available',logical(soft_ref.available), ...
    'soft_excess_sq_mean',double(soft_ref.mean), ...
    'soft_excess_sq_integral_s',double(soft_ref.integral_s), ...
    'soft_budget_W',double(soft_ref.budget_W), ...
    'soft_reference_source',char(soft_ref.source));
end

function [R,valid]=soft_reference_from_fairness_local(F)
R=empty_soft_reference_local();
valid=false;
required={'noguard_soft_reference_available', ...
    'noguard_soft_excess_sq_mean', ...
    'noguard_soft_excess_sq_integral_s', ...
    'noguard_soft_budget_W','noguard_soft_reference_source'};
if ~isstruct(F) || ~all(isfield(F,required)) || ...
        ~is_binary_scalar_local(F.noguard_soft_reference_available) || ...
        ~logical(F.noguard_soft_reference_available)
    return;
end
mean_value=F.noguard_soft_excess_sq_mean;
integral_value=F.noguard_soft_excess_sq_integral_s;
budget=F.noguard_soft_budget_W;
source=F.noguard_soft_reference_source;
if ~is_nonnegative_finite_scalar_local(mean_value) || ...
        ~is_nonnegative_finite_scalar_local(integral_value) || ...
        ~is_positive_finite_scalar_local(budget) || ...
        ~is_text_scalar_local(source) || ...
        ~strcmp(char(string(source)), ...
            'execution_hard_audit_pavg_replay_v2_normalized_square')
    return;
end
R.available=true;
R.mean=double(mean_value);
R.integral_s=double(integral_value);
R.budget_W=double(budget);
R.source=char(string(source));
valid=true;
end

function R=soft_reference_from_output_local(out)
R=empty_soft_reference_local();
if ~isstruct(out) || ~isfield(out,'execution_audit') || ...
        ~isstruct(out.execution_audit) || ...
        ~isscalar(out.execution_audit)
    return;
end
A=out.execution_audit;
required={'Pavg_replay_available','Pavg_replay_authoritative', ...
    'Pavg_replay_schema', ...
    'Pgrid_avg_budget_W','Pgrid_avg_excess_sq_norm_mean', ...
    'Pgrid_avg_excess_sq_norm_integral_s'};
if ~all(isfield(A,required)) || ...
        ~is_binary_scalar_local(A.Pavg_replay_available) || ...
        ~logical(A.Pavg_replay_available) || ...
        ~is_binary_scalar_local(A.Pavg_replay_authoritative) || ...
        ~logical(A.Pavg_replay_authoritative) || ...
        ~is_text_scalar_local(A.Pavg_replay_schema) || ...
        ~strcmp(char(string(A.Pavg_replay_schema)), ...
            'execution_hard_audit_pavg_replay_v2_normalized_square') || ...
        ~is_positive_finite_scalar_local(A.Pgrid_avg_budget_W) || ...
        ~is_nonnegative_finite_scalar_local( ...
            A.Pgrid_avg_excess_sq_norm_mean) || ...
        ~is_nonnegative_finite_scalar_local( ...
            A.Pgrid_avg_excess_sq_norm_integral_s)
    return;
end
if ~isfield(out,'log') || ~isstruct(out.log) || ...
        ~isfield(out.log,'t') || ~isnumeric(out.log.t) || ...
        ~isreal(out.log.t) || ~isvector(out.log.t) || ...
        ~isfield(A,'Pgrid_avg_replay_W') || ...
        ~isnumeric(A.Pgrid_avg_replay_W) || ...
        ~isreal(A.Pgrid_avg_replay_W) || ...
        ~isvector(A.Pgrid_avg_replay_W)
    return;
end
t=double(out.log.t(:));
pavg=double(A.Pgrid_avg_replay_W(:));
if isempty(t) || numel(t)~=numel(pavg) || ...
        any(~isfinite(t)) || any(~isfinite(pavg)) || ...
        t(1)<=0 || any(diff(t)<=0)
    return;
end
dt=[t(1);diff(t)];
pbud=double(A.Pgrid_avg_budget_W);
sq=(max(pavg-pbud,0)./pbud).^2;
integral_check=sum(dt.*sq);
mean_check=integral_check/max(sum(dt),eps);
tol=1e-12+1e-10*max([1,integral_check,mean_check]);
if abs(integral_check-double( ...
        A.Pgrid_avg_excess_sq_norm_integral_s))>tol || ...
        abs(mean_check-double( ...
        A.Pgrid_avg_excess_sq_norm_mean))>tol
    return;
end
R.available=true;
R.mean=double(A.Pgrid_avg_excess_sq_norm_mean);
R.integral_s=double(A.Pgrid_avg_excess_sq_norm_integral_s);
R.budget_W=double(A.Pgrid_avg_budget_W);
R.source='execution_hard_audit_pavg_replay_v2_normalized_square';
end

function R=empty_soft_reference_local()
R=struct('available',false,'mean',NaN,'integral_s',NaN, ...
    'budget_W',NaN,'source','unavailable');
end

function tf=is_binary_scalar_local(v)
tf=(islogical(v)||isnumeric(v)) && isreal(v) && isscalar(v) && ...
    isfinite(double(v)) && any(double(v)==[0 1]);
end

function tf=is_nonnegative_finite_scalar_local(v)
tf=isnumeric(v) && isreal(v) && isscalar(v) && ...
    isfinite(double(v)) && double(v)>=0;
end

function tf=is_positive_finite_scalar_local(v)
tf=is_nonnegative_finite_scalar_local(v) && double(v)>0;
end

function tf=is_text_scalar_local(v)
tf=(ischar(v) && isrow(v) && ~isempty(v)) || ...
    (isstring(v) && isscalar(v) && strlength(v)>0);
end

function tf = is_binary_true_local(v)
tf = (islogical(v) || isnumeric(v)) && isscalar(v) && ...
    isfinite(double(v)) && double(v)==1;
end

function v = double_or_nan_local(v)
if isnumeric(v) && isscalar(v) && isfinite(v) && v > 0
    v = double(v);
else
    v = NaN;
end
end

function v = getdef_local(S,fn,def)
if isstruct(S) && isfield(S,fn) && ~isempty(S.(fn)), v=S.(fn); else, v=def; end
end
