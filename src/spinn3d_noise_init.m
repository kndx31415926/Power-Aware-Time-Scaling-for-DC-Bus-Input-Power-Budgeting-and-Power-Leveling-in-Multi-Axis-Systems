function state = spinn3d_noise_init(cfg,nJ)
%SPINN3D_NOISE_INIT Central plant/measurement-noise state for every demo.

rng_mode = lower(char(string(cfg.NOISE.rng_mode)));

noise_stream = [];
if strcmp(rng_mode,'local')
    seed = double(cfg.NOISE.seed);

    noise_stream = RandStream('mt19937ar','Seed',seed);
end

state = struct( ...
    'sigma_q',double(cfg.NOISE.sigma_q), ...
    'sigma_dq',double(cfg.NOISE.sigma_dq), ...
    'tau_std',double(cfg.NOISE.tau_std), ...
    'servo_hold_s',double(cfg.SERVO_HOLD_T), ...
    'tau_hold',zeros(1,nJ), ...
    'elapsed_s',0.0, ...
    'rng_mode',rng_mode, ...
    'stream',noise_stream, ...
    'nJ',double(nJ));
end
